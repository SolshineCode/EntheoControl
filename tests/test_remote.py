def test_apply_basic_controls():
    st, corners = st_default(), [list(c) for c in UNIT]
    acts = apply_commands(
        [{"cmd": "fold", "i": 7}, {"cmd": "mode", "i": 0}, {"cmd": "fb", "on": False},
         {"cmd": "fbAmt", "v": 0.4}, {"cmd": "next"}, {"cmd": "grid", "on": True}],
        st, corners, n_folds=9)
    assert acts == set()
    assert (st["fold_i"], st["mode"], st["fb"], st["fbAmt"], st["next"], st["grid"]) == (7, 0, False, 0.4, True, True)
    apply_commands([{"cmd": "fold", "i": 20}], st, corners, n_folds=9)
    assert st["fold_i"] == 7  # out of range for this FOLDS list: ignored
    apply_commands([{"cmd": "calib", "on": True}], st, corners)
    assert st["calib"] and st["grid"]
    apply_commands([{"cmd": "calib", "on": False}], st, corners)
    assert not st["calib"] and not st["grid"]


def test_apply_corner_nudge_reset_save():
    st, corners = st_default(), [list(c) for c in UNIT]
    ident = corners
    acts = apply_commands([{"cmd": "corner", "i": 2, "u": 0.9, "v": 0.8}], st, corners)
    assert corners[2] == [0.9, 0.8] and acts == set()
    apply_commands([{"cmd": "nudge", "i": 2, "du": 0.01, "dv": -0.01}], st, corners)
    assert corners[2] == pytest.approx([0.91, 0.79])
    apply_commands([{"cmd": "nudge", "i": 0, "du": -0.05, "dv": -0.05}], st, corners)
    assert corners[0] == [0.0, 0.0]  # nudges clamp at the screen edge
    assert apply_commands([{"cmd": "save"}], st, corners) == {"save"}
    apply_commands([{"cmd": "reset"}], st, corners)
    assert corners == UNIT and corners is ident  # mutated in place (the GL loop holds this list)


def test_apply_rejects_degenerate_quads():
    st, corners = st_default(), [list(c) for c in UNIT]
    # top-right dragged onto bottom-left -> collinear/flipped -> singular homography; must be ignored
    apply_commands([{"cmd": "corner", "i": 2, "u": 0.0, "v": 0.0}], st, corners)
    assert corners == UNIT
    apply_commands([{"cmd": "corner", "i": 2, "u": 0.2, "v": 0.1}], st, corners)  # concave / bow-tie
    assert corners == UNIT
    assert rcmod.quad_ok(UNIT)
    assert rcmod.quad_ok(UNIT[::-1])  # mirrored (rear projection) is still a valid quad
    assert not rcmod.quad_ok([[0, 0], [1, 0], [0, 0], [0, 1]])
    assert not rcmod.quad_ok([[0, 0], [1, 1], [1, 0], [0, 1]])


