def raw_request(port, head, body=b"", wait=5.0):
    """Send raw bytes, return (status code, whole reply). The body may be shorter than Content-Length."""
    s = socket.create_connection(("127.0.0.1", port), timeout=wait)
    try:
        s.sendall(head.encode() + body)
        data = b""
        while True:
            chunk = s.recv(65536)
            if not chunk:
                break
            data += chunk
    except OSError:
        pass
    finally:
        s.close()
    return (int(data.split(b" ", 2)[1]) if data.startswith(b"HTTP/") else 0), data


def test_oversize_and_tokenless_uploads_are_refused_before_the_body_is_read(arc):
    import time
    big = rcmod.MAX_UPLOAD + 5
    t0 = time.time()
    code, _ = raw_request(arc.port, f"POST /upload?k=tok123 HTTP/1.1\r\nHost: x\r\nContent-Length: {big}\r\n\r\n", b"x")
    assert code == 413                                                       # a real 413, answered without the body
    code, _ = raw_request(arc.port, "POST /upload HTTP/1.1\r\nHost: x\r\nContent-Length: 20000000\r\n\r\n", b"x")
    assert code == 403                                                       # no token: rejected before any body
    code, _ = raw_request(arc.port, "POST /cmd?k=bad HTTP/1.1\r\nHost: x\r\nContent-Length: 4000\r\n\r\n")
    assert code == 403
    assert time.time() - t0 < 3                                              # none of them waited for the missing bytes
    assert http(base(arc) + "/upload?k=tok123", png_bytes(), raw=True)[0] == 200


