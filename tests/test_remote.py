def test_upload_asks_the_worker_for_a_depth_map(arc):
    import threading
    from http.server import BaseHTTPRequestHandler, ThreadingHTTPServer
    seen = []

    class H(BaseHTTPRequestHandler):
        def log_message(self, *a):
            pass

        def do_POST(self):
            body = self.rfile.read(int(self.headers.get("Content-Length", 0)))
            seen.append((self.path, self.headers.get("X-Token"), json.loads(body)))
            self.send_response(200)
            self.send_header("Content-Length", "2")
            self.end_headers()
            self.wfile.write(b"{}")

    srv = ThreadingHTTPServer(("127.0.0.1", 0), H)
    threading.Thread(target=srv.serve_forever, daemon=True).start()
    try:
        (arc.tmp / ".remote_token").write_text("worker-token\n")
        arc.ai_url = f"http://127.0.0.1:{srv.server_address[1]}"
        name = json.loads(http(base(arc) + "/upload?k=tok123", png_bytes(), raw=True)[1])["name"]
        import time
        t0 = time.time()
        while not seen and time.time() - t0 < 5:
            time.sleep(0.02)
        assert seen == [("/depth", "worker-token", {"name": name})]
    finally:
        srv.shutdown()
        srv.server_close()


